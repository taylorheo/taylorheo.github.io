/* Markdown rendering                                                          */
/* -------------------------------------------------------------------------- */
function createRenderer() {
  const headings = [];
  const used = new Map();
  const uniqueId = base => {
    const id = slugify(base) || 'section';
    const n = used.get(id) ?? 0;
    used.set(id, n + 1);
    return n ? `${id}-${n}` : id;
  };
  const renderer = {
    heading({ tokens, depth }) {
      const html = this.parser.parseInline(tokens);
      const text = plainText(html);
      const id = uniqueId(text);
      if (depth >= 2 && depth <= 3) headings.push({ depth, id, text });
      return `<h${depth} id="${esc(id)}"><a class="post__anchor" href="#${esc(id)}" aria-label="${esc(text)} 섹션 링크">#</a>${html}</h${depth}>\n`;
    },
    code({ text, lang }) {
      const language = (lang || '').trim().split(/\s+/)[0].toLowerCase();
      let body, cls = '';
      if (language && hljs.getLanguage(language)) {
        body = hljs.highlight(text, { language, ignoreIllegals: true }).value;
        cls = ` class="hljs language-${esc(language)}"`;
      } else if (text.length < 20000) {
        const auto = hljs.highlightAuto(text);
        body = auto.value; cls = ` class="hljs${auto.language ? ` language-${esc(auto.language)}` : ''}"`;
      } else {
        body = esc(text); cls = ' class="hljs"';
      }
      const label = language ? `<span class="post__code-lang">${esc(language)}</span>` : '';
      return `<div class="post__code">${label}<button type="button" class="post__copy" data-copy-code aria-label="코드 복사">Copy</button><pre><code${cls}>${body}</code></pre></div>\n`;
    },
    image({ href, title, text }) {
      const t = title ? ` title="${esc(title)}"` : '';
      return `<img src="${esc(href)}" alt="${esc(text || '')}"${t} loading="lazy" decoding="async">`;
    },
    link({ href, title, tokens }) {
      const html = this.parser.parseInline(tokens);
      const external = /^https?:\/\//i.test(href) && !href.startsWith(SITE.url);
      const t = title ? ` title="${esc(title)}"` : '';
      const ext = external ? ' target="_blank" rel="noopener noreferrer"' : '';
      return `<a href="${esc(href)}"${t}${ext}>${html}</a>`;
    },
    table({ header, rows }) {
      const cell = (c, tag) => `<${tag}${c.align ? ` style="text-align:${c.align}"` : ''}>${this.parser.parseInline(c.tokens)}</${tag}>`;
      const head = `<thead><tr>${header.map(c => cell(c, 'th')).join('')}</tr></thead>`;
      const body = rows.map(r => `<tr>${r.map(c => cell(c, 'td')).join('')}</tr>`).join('');
      return `<div class="post__table"><table>${head}<tbody>${body}</tbody></table></div>\n`;
    }
  };
  return { renderer, headings };
}

export function sanitizeHtml(html) {
  return String(html)
    .replace(/<script\b[\s\S]*?<\/script>/gi, '')
    .replace(/<(iframe)\b([^>]*)>/gi, (m, tag, attrs) => /src=["']https:\/\/(www\.)?(youtube\.com|youtube-nocookie\.com)\//i.test(attrs) ? m : '')
    .replace(/\son[a-z]+\s*=\s*("[^"]*"|'[^']*'|[^\s>]+)/gi, '')
    .replace(/\s(href|src)\s*=\s*(["']?)\s*javascript:[^"'\s>]*\2/gi, ' $1=$2#$2');
}

export function renderMarkdown(md) {
  const { renderer, headings } = createRenderer();
  const instance = new Marked({ gfm: true, breaks: true });
  instance.use({ renderer });
  const html = sanitizeHtml(instance.parse(md ?? ''));
  return { html, headings };
}

