/* Local markdown posts                                                       */
/* -------------------------------------------------------------------------- */
function loadLocalPosts() {
  if (!existsSync(POSTS_DIR)) return [];
  const files = readdirSync(POSTS_DIR).filter(f => /\.(md|markdown)$/i.test(f) && !f.startsWith('_') && f.toLowerCase() !== 'readme.md').sort();
  const posts = [];
  for (const file of files) {
    const raw = readFileSync(join(POSTS_DIR, file), 'utf8');
    const { meta, body } = parseFrontMatter(raw);
    if (meta.draft === true) { log('draft 건너뜀:', file); continue; }
    const base = basename(file).replace(/\.(md|markdown)$/i, '');
    const dateFromName = base.match(/^(\d{4}-\d{2}-\d{2})[-_]?/);
    const rawDate = meta.date ?? dateFromName?.[1];
    if (!rawDate) throw new Error(`${file}: front matter에 date가 없고 파일명에도 날짜(YYYY-MM-DD-)가 없습니다.`);
    const date = new Date(rawDate);
    if (Number.isNaN(date.getTime())) throw new Error(`${file}: date 형식을 해석할 수 없습니다 (${rawDate}).`);
    const titleFromBody = body.match(/^#\s+(.+)$/m)?.[1];
    const title = meta.title ?? titleFromBody;
    if (!title) throw new Error(`${file}: front matter에 title이 없고 본문에 H1도 없습니다.`);
    const slug = slugify(meta.slug ?? (dateFromName ? base.slice(dateFromName[0].length) : base));
    if (!slug) throw new Error(`${file}: slug를 만들 수 없습니다. front matter에 slug를 지정하세요.`);
    let content = body;
    if (!meta.title && titleFromBody) content = body.replace(/^#\s+.+$\n?/m, '');
    const tags = Array.isArray(meta.tags) ? meta.tags : typeof meta.tags === 'string' ? meta.tags.split(',').map(s => s.trim()).filter(Boolean) : [];
    posts.push({
      source: 'site', file, slug, title, body: content,
      description: meta.description ?? meta.summary ?? '',
      tags, thumbnail: meta.thumbnail ?? meta.image ?? null, series: meta.series ?? null,
      date: date.toISOString(), updated: meta.updated ? new Date(meta.updated).toISOString() : null,
      lang: meta.lang === 'en' ? 'en' : 'ko', canonical: meta.canonical ?? null
    });
  }
  return posts;
}

