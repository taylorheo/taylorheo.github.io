function renderTemplate(tpl, vars) {
  return tpl.replace(/\{\{(\w+)\}\}/g, (_, k) => (k in vars ? String(vars[k]) : ''));
}

function listGeneratedDirs() {
  if (!existsSync(BLOG_DIR)) return [];
  return readdirSync(BLOG_DIR).filter(name => {
    const p = join(BLOG_DIR, name, 'index.html');
    if (!statSync(join(BLOG_DIR, name)).isDirectory() || !existsSync(p)) return false;
    return readFileSync(p, 'utf8').includes(GENERATED_MARK);
  });
}

export async function build() {
  const template = readFileSync(TEMPLATE, 'utf8');
  const velog = await loadVelogPosts();
  const local = loadLocalPosts();

  const all = [];
  const seen = new Map();
  for (const p of velog) {
    const slug = safeDirName(p.slug);
    if (!slug || SITE.reservedSlugs.has(slug)) { warn('예약된 slug, 건너뜀:', p.slug); continue; }
    seen.set(slug, 'velog');
    all.push({ ...p, source: 'velog', slug, lang: 'ko', canonical: p.url });
  }
  for (const p of local) {
    if (SITE.reservedSlugs.has(p.slug)) throw new Error(`${p.file}: '${p.slug}'는 예약된 경로입니다. 다른 slug를 지정하세요.`);
    if (seen.has(p.slug)) throw new Error(`${p.file}: slug '${p.slug}'가 ${seen.get(p.slug)} 글과 겹칩니다. front matter의 slug를 바꿔주세요.`);
    seen.set(p.slug, 'site');
    all.push(p);
  }
  all.sort((a, b) => new Date(b.date) - new Date(a.date));

  // 렌더링
  const rendered = all.map(p => {
    let html, headings = [];
    if (p.body != null) ({ html, headings } = renderMarkdown(p.body));
    else { html = sanitizeHtml(p.html || ''); }
    const plain = p.body != null ? stripMarkdown(p.body) : stripMarkdown(html);
    return {
      ...p, html, headings,
      description: p.description || excerpt(p.body ?? plain, 160),
      readingMinutes: p.body != null ? readingMinutes(p.body) : Math.max(1, Math.round(plain.length / 500)),
      pagePath: `/blog/${encodeURIComponent(p.slug)}/`
    };
  });

  const index = rendered.map(p => ({
    slug: p.slug, source: p.source, title: p.title, description: p.description,
    date: p.date, updated: p.updated ?? null, tags: p.tags ?? [], series: p.series ?? null,
    thumbnail: p.thumbnail ?? null, readingMinutes: p.readingMinutes, lang: p.lang,
    url: p.pagePath, canonical: p.canonical ?? `${SITE.url}${p.pagePath}`
  }));

  const outputs = new Map();
  const tagCounts = {};
  for (const p of index) for (const t of p.tags) tagCounts[t] = (tagCounts[t] || 0) + 1;
  const indexJson = { site: SITE.url, count: index.length, tags: tagCounts, posts: index };
  outputs.set(join(DATA_DIR, 'posts.json'), JSON.stringify(indexJson, null, 2) + '\n');
  outputs.set(join(DATA_DIR, 'posts.js'), `/* generated by scripts/build-blog.mjs */\nwindow.BLOG_POSTS = ${JSON.stringify(indexJson)};\n`);

  rendered.forEach((p, i) => {
    const prev = rendered[i + 1], next = rendered[i - 1];
    const toc = p.headings.length >= 2
      ? `<nav class="post__toc" aria-labelledby="tocHeading"><p class="post__toc-heading" id="tocHeading" data-i18n="blog.toc">목차</p><ol>${p.headings.map(h => `<li class="post__toc-item post__toc-item--${h.depth}"><a href="#${esc(h.id)}">${esc(h.text)}</a></li>`).join('')}</ol></nav>`
      : '';
    const tags = p.tags?.length ? `<ul class="post__tags" role="list">${p.tags.map(t => `<li><a class="e-chip" href="../?tag=${encodeURIComponent(t)}">${esc(t)}</a></li>`).join('')}</ul>` : '';
    const sourceBadge = p.source === 'velog'
      ? `<span class="post__source post__source--velog">velog</span>`
      : `<span class="post__source post__source--site" data-i18n="blog.source.site">이 사이트</span>`;
    const canonicalNote = p.source === 'velog'
      ? `<p class="post__origin"><span data-i18n="blog.originVelog">이 글은 velog에 처음 게시되었습니다.</span> <a href="${esc(p.url)}" target="_blank" rel="noopener noreferrer"><span data-i18n="blog.viewOnVelog">velog에서 원문 보기</span> ↗</a></p>`
      : '';
    const navLink = (post, cls, label) => post
      ? `<a class="post__nav-link ${cls}" href="../${encodeURIComponent(post.slug)}/"><span class="post__nav-label" data-i18n="${label}">${label === 'blog.prev' ? '이전 글' : '다음 글'}</span><span class="post__nav-title">${esc(post.title)}</span></a>`
      : `<span class="post__nav-link ${cls} post__nav-link--empty"></span>`;
    const bodyHasThumb = p.thumbnail && (p.body ?? p.html ?? '').includes(p.thumbnail);
    const thumb = p.thumbnail && !bodyHasThumb ? `<figure class="post__hero"><img src="${esc(p.thumbnail)}" alt="" loading="eager" decoding="async"></figure>` : '';
    const html = renderTemplate(template, {
      GENERATED_MARK,
      root: '../../',
      lang: p.lang,
      title: esc(p.title),
      pageTitle: esc(`${p.title} — 허영대 블로그`),
      description: esc(p.description),
      canonical: esc(p.canonical ?? `${SITE.url}${p.pagePath}`),
      pageUrl: esc(`${SITE.url}${p.pagePath}`),
      ogImage: esc(p.thumbnail || `${SITE.url}/og-image.png`),
      datetime: esc(p.date),
      dateKo: fmtDate(p.date, 'ko'),
      dateEn: fmtDate(p.date, 'en'),
      updatedRow: p.updated && fmtDate(p.updated) !== fmtDate(p.date) ? `<span class="post__meta-sep" aria-hidden="true">·</span><span><span data-i18n="blog.updated">수정</span> <time datetime="${esc(p.updated)}" data-date-ko="${fmtDate(p.updated, 'ko')}" data-date-en="${fmtDate(p.updated, 'en')}">${fmtDate(p.updated, 'ko')}</time></span>` : '',
      readingMinutes: p.readingMinutes,
      sourceBadge, tags, toc, canonicalNote, thumb,
      content: p.html,
      prevLink: navLink(prev, 'post__nav-link--prev', 'blog.prev'),
      nextLink: navLink(next, 'post__nav-link--next', 'blog.next'),
      jsonLd: JSON.stringify({
        '@context': 'https://schema.org', '@type': 'BlogPosting', headline: p.title, description: p.description,
        datePublished: p.date, dateModified: p.updated || p.date, inLanguage: p.lang,
        author: { '@type': 'Person', name: SITE.author, url: SITE.url }, image: p.thumbnail || undefined,
        mainEntityOfPage: `${SITE.url}${p.pagePath}`, url: p.canonical, keywords: p.tags?.join(', ') || undefined
      }).replace(/</g, '\\u003c')
    });
    outputs.set(join(BLOG_DIR, p.slug, 'index.html'), html);
  });

  // RSS feed
  const feedItems = rendered.map(p => `    <item>
      <title><![CDATA[${p.title}]]></title>
      <link>${esc(SITE.url + p.pagePath)}</link>
      <guid isPermaLink="false">${esc(`${p.source}:${p.slug}`)}</guid>
      <pubDate>${new Date(p.date).toUTCString()}</pubDate>
      ${p.tags.map(t => `<category><![CDATA[${t}]]></category>`).join('')}
      <description><![CDATA[${p.description}]]></description>
      <content:encoded><![CDATA[${p.html.replace(/\]\]>/g, ']]]]><![CDATA[>')}]]></content:encoded>
    </item>`).join('\n');
  outputs.set(join(BLOG_DIR, 'feed.xml'), `<?xml version="1.0" encoding="utf-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom" xmlns:content="http://purl.org/rss/1.0/modules/content/">
  <channel>
    <title>${esc(SITE.title)}</title>
    <link>${SITE.url}/blog/</link>
    <description>${esc(SITE.description)}</description>
    <language>ko</language>
    <lastBuildDate>${new Date(rendered[0]?.date ?? Date.now()).toUTCString()}</lastBuildDate>
    <atom:link href="${SITE.url}/blog/feed.xml" rel="self" type="application/rss+xml"/>
${feedItems}
  </channel>
</rss>
`);

  // Sitemap
  outputs.set(join(BLOG_DIR, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <url><loc>${SITE.url}/</loc></url>
  <url><loc>${SITE.url}/blog/</loc>${rendered[0] ? `<lastmod>${rendered[0].date.slice(0, 10)}</lastmod>` : ''}</url>
${rendered.map(p => `  <url><loc>${esc(SITE.url + p.pagePath)}</loc><lastmod>${(p.updated || p.date).slice(0, 10)}</lastmod></url>`).join('\n')}
</urlset>
`);

  // 오래된 생성물 제거 대상
  const keep = new Set(rendered.map(p => p.slug));
  const stale = listGeneratedDirs().filter(d => !keep.has(d));

  if (CHECK) {
    const diffs = [];
    for (const [file, content] of outputs) {
      if (!existsSync(file) || readFileSync(file, 'utf8') !== content) diffs.push(file.replace(ROOT + '/', ''));
    }
    diffs.push(...stale.map(d => `blog/${d}/ (stale)`));
    if (diffs.length) { console.error('[blog] 생성물이 최신이 아닙니다:\n  ' + diffs.join('\n  ')); process.exit(1); }
    log('생성물이 최신입니다.');
    return { posts: index };
  }

  for (const [file, content] of outputs) { mkdirSync(dirname(file), { recursive: true }); writeFileSync(file, content); }
  for (const d of stale) { rmSync(join(BLOG_DIR, d), { recursive: true, force: true }); log('오래된 글 페이지 삭제:', d); }
  log(`빌드 완료: velog ${velog.length}건 + 사이트 ${local.length}건 = ${index.length}건`);
  return { posts: index };
}

