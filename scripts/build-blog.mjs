async function gql(query, variables) {
  const res = await fetch(SITE.velogGraphql, {
    method: 'POST',
    headers: { 'content-type': 'application/json', 'user-agent': 'taylorheo.github.io blog sync' },
    body: JSON.stringify({ query, variables }),
    signal: AbortSignal.timeout(20000)
  });
  if (!res.ok) throw new Error(`velog GraphQL HTTP ${res.status}`);
  const json = await res.json();
  if (json.errors?.length) throw new Error('velog GraphQL: ' + json.errors.map(e => e.message).join('; '));
  return json.data;
}

async function fetchVelogViaGraphql() {
  const list = [];
  let cursor = null;
  for (let page = 0; page < 50; page++) {
    const data = await gql(`query Posts($input: GetPostsInput!) {
      posts(input: $input) { id title short_description thumbnail url_slug released_at updated_at tags is_private }
    }`, { input: { username: SITE.velogUser, limit: 20, cursor } });
    const batch = data?.posts ?? [];
    list.push(...batch.filter(p => !p.is_private));
    if (batch.length < 20) break;
    cursor = batch[batch.length - 1].id;
  }
  const posts = [];
  for (const p of list) {
    const data = await gql(`query ReadPost($input: ReadPostInput!) {
      post(input: $input) { id title body url_slug released_at updated_at tags thumbnail short_description series { name url_slug } }
    }`, { input: { username: SITE.velogUser, url_slug: p.url_slug } });
    const full = data?.post;
    if (!full?.body) { warn('본문 없음, 건너뜀:', p.url_slug); continue; }
    posts.push({
      id: full.id,
      title: full.title,
      slug: full.url_slug,
      url: `https://velog.io/@${SITE.velogUser}/${encodeURIComponent(full.url_slug)}`,
      body: full.body,
      description: full.short_description || '',
      tags: full.tags || [],
      thumbnail: full.thumbnail || null,
      series: full.series?.name || null,
      date: full.released_at,
      updated: full.updated_at
    });
  }
  return posts;
}

async function fetchVelogViaRss() {
  const res = await fetch(SITE.velogRss, { signal: AbortSignal.timeout(20000) });
  if (!res.ok) throw new Error(`velog RSS HTTP ${res.status}`);
  const xml = await res.text();
  const items = [...xml.matchAll(/<item>([\s\S]*?)<\/item>/g)].map(m => m[1]);
  const pick = (block, tag) => {
    const m = block.match(new RegExp(`<${tag}>(?:<!\\[CDATA\\[)?([\\s\\S]*?)(?:\\]\\]>)?<\\/${tag}>`));
    return m ? m[1].trim() : '';
  };
  return items.map(block => {
    const link = pick(block, 'link');
    const slug = decodeURIComponentSafe(link.split('/').pop() || '');
    return {
      id: pick(block, 'guid') || link,
      title: pick(block, 'title'),
      slug,
      url: link,
      body: null,
      html: pick(block, 'description'),
      description: '',
      tags: [],
      thumbnail: null,
      series: null,
      date: new Date(pick(block, 'pubDate')).toISOString(),
      updated: null
    };
  });
}

async function loadVelogPosts() {
  const cached = existsSync(VELOG_CACHE) ? JSON.parse(readFileSync(VELOG_CACHE, 'utf8')) : null;
  if (OFFLINE) {
    log(`offline 모드: velog 캐시 ${cached?.posts?.length ?? 0}건 사용`);
    return cached?.posts ?? [];
  }
  try {
    const posts = await fetchVelogViaGraphql();
    log(`velog GraphQL: ${posts.length}건 수집`);
    mkdirSync(DATA_DIR, { recursive: true });
    writeFileSync(VELOG_CACHE, JSON.stringify({ source: 'graphql', user: SITE.velogUser, posts }, null, 2) + '\n');
    return posts;
  } catch (e) {
    warn('velog GraphQL 실패:', e.message);
  }
  try {
    const posts = await fetchVelogViaRss();
    log(`velog RSS 폴백: ${posts.length}건 수집 (본문은 RSS HTML)`);
    // RSS 결과는 캐시보다 정보가 적으므로, 캐시가 있으면 캐시 본문을 우선 사용
    if (cached?.posts?.length) {
      const bySlug = new Map(cached.posts.map(p => [p.slug, p]));
      return posts.map(p => bySlug.get(p.slug) ?? p).concat(cached.posts.filter(p => !posts.some(q => q.slug === p.slug)));
    }
    return posts;
  } catch (e) {
    warn('velog RSS 실패:', e.message);
  }
  if (cached?.posts) { warn(`네트워크 실패 — 캐시 ${cached.posts.length}건 사용`); return cached.posts; }
  warn('velog 글을 가져오지 못했고 캐시도 없습니다. velog 글 없이 빌드합니다.');
  return [];
}

