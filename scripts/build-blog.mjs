export function slugify(input) {
  return String(input ?? '')
    .normalize('NFC')
    .trim()
    .toLowerCase()
    .replace(/[\s_]+/g, '-')
    .replace(/[^\p{L}\p{N}-]+/gu, '')
    .replace(/-{2,}/g, '-')
    .replace(/^-+|-+$/g, '');
}
function safeDirName(slug) {
  // velog slug은 원형을 유지하되 파일시스템/URL에 위험한 문자만 제거
  return decodeURIComponentSafe(slug).normalize('NFC').replace(/[\/\\?#%<>:"|*\s]+/g, '-').replace(/^\.+/, '').replace(/-{2,}/g, '-').replace(/^-+|-+$/g, '');
}
function decodeURIComponentSafe(s) { try { return decodeURIComponent(s); } catch { return s; } }

export function stripMarkdown(md) {
  return String(md ?? '')
    .replace(/```[\s\S]*?```/g, ' ')
    .replace(/`[^`]*`/g, ' ')
    .replace(/!\[[^\]]*\]\([^)]*\)/g, ' ')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/<[^>]+>/g, ' ')
    .replace(/^[#>\-*+\d.\s|]+/gm, '')
    .replace(/[*_~]+/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}
export function excerpt(md, max = 160) {
  const text = stripMarkdown(md);
  if (text.length <= max) return text;
  return text.slice(0, max).replace(/\s+\S*$/, '') + '…';
}
export function readingMinutes(md) {
  const text = stripMarkdown(md);
  const cjk = (text.match(/[\u3131-\uD79D\u4E00-\u9FFF\u3040-\u30FF]/g) || []).length;
  const words = text.replace(/[\u3131-\uD79D\u4E00-\u9FFF\u3040-\u30FF]/g, ' ').split(/\s+/).filter(Boolean).length;
  return Math.max(1, Math.round(cjk / 500 + words / 200));
}
const fmtDate = (iso, lang = 'ko') => {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return '';
  const ymd = new Intl.DateTimeFormat('sv-SE', { timeZone: 'Asia/Seoul', year: 'numeric', month: '2-digit', day: '2-digit' }).format(d); // YYYY-MM-DD
  return lang === 'en' ? ymd : ymd.replace(/-/g, '.');
};
const plainText = html => String(html ?? '').replace(/<[^>]+>/g, '').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/\s+/g, ' ').trim();

